-- Ведущий группы как ссылка на человека (справочник людей), а не только имя текстом. Раньше «кто ведёт» вычислялось
-- по совпадению имени и телефона, то есть угадывалось. Теперь, когда обращение «уже веду группу» сверено со справочником
-- групп, группа получает ссылку на регистрацию ведущего — и в одной цепочке видно «группа — ведущий — его люди».
-- Имя и телефон ведущего в самой группе остаются как были: так записано в таблице церкви, и по ним группы ищут.
ALTER TABLE groups ADD COLUMN leader_user_id bigint REFERENCES users(id) ON DELETE SET NULL;
CREATE INDEX groups_leader_user_idx ON groups (leader_user_id) WHERE leader_user_id IS NOT NULL;
