-- Метка «Странный человек»: координатор или распределитель ставит её после обзвона, когда становится понятно, что у
-- человека есть особенности, и для него нужна отдельная группа. Метка видна везде, где виден человек (заявки, «Люди»,
-- состав групп), и такие заявки не попадают в автоматический подбор обычных групп.
--
-- Метка привязана к человеку по тому же ключу, что и справочник людей: u12 — регистрация, r345 — человек из заявки без
-- регистрации, p7 — карточка, внесённая вручную. Строка есть — метка стоит; убрали — строку удаляют (история в журнале
-- действий). Заметка нужна для коллег («что заметили»), в журнал она не попадает.
CREATE TABLE strange_marks (
  person_key text PRIMARY KEY CHECK (person_key ~ '^[urp][0-9]{1,15}$'),
  note       text,
  set_by     text NOT NULL,
  set_at     timestamptz NOT NULL DEFAULT now()
);
