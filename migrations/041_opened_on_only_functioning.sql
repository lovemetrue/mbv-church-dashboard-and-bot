-- Росток — признак новизны именно действующей группы: «Потенциальная», «На паузе», «Кампания» и прочие его не получают.
-- Поэтому дату открытия база ставит, только когда группа становится «Функционирует»: заведена такой не из выгрузки таблицы
-- (бот, форма) или переведена из «Потенциальной». Возобновление группы с паузы новым открытием не считается.
-- Даты, которые уже поставила миграция 040 группам в других статусах, остаются: на экране они ни на что не влияют, пока группа
-- не станет действующей, а вручную поправить («Дата открытия») их можно.
CREATE OR REPLACE FUNCTION groups_set_opened_on() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.opened_on IS NULL AND NEW.status = 'Функционирует' THEN
    IF TG_OP = 'INSERT' AND NEW.source <> 'таблица' THEN
      NEW.opened_on := current_date;
    ELSIF TG_OP = 'UPDATE' AND OLD.status = 'Потенциальная' THEN
      NEW.opened_on := current_date;
    END IF;
  END IF;
  RETURN NEW;
END;
$$;
