-- Сколько мест в группе. У групп оно разное, а раньше было одно на всех (HG_DEFAULT_CAPACITY, 10): свободные места,
-- «нет мест» при утверждении и подбор считали от него. Пусто — по-прежнему общее значение, поэтому существующие группы
-- без правки ведут себя как раньше.
ALTER TABLE groups ADD COLUMN IF NOT EXISTS capacity integer CHECK (capacity BETWEEN 1 AND 200);
