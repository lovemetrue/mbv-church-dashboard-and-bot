-- Пол человека: мужчине не предлагают женскую группу, женщине — мужскую.
--
-- В анкете пола нет, поэтому сервер выводит его из ФИО (src/core/gender.ts) на лету, и в базе он не хранится. Здесь —
-- только то, что поставили вручную или по подсказке модели: ручной выбор всегда важнее ФИО (оно бывает записано
-- неоднозначно — «Саша Ким»). Строки нет — пол берётся из ФИО, а если не понять — пустой, и служителю показывается
-- «Пол не указан».
--
-- Привязка — по тому же ключу человека, что у метки «Странный человек» (миграция 031): u12 — регистрация, r345 —
-- человек из заявки без регистрации, p7 — карточка. set_by: логин служителя или «ии» — подсказка модели, которую
-- стоит проверить.
CREATE TABLE person_genders (
  person_key text PRIMARY KEY CHECK (person_key ~ '^[urp][0-9]{1,15}$'),
  gender     text NOT NULL CHECK (gender IN ('м', 'ж')),
  set_by     text NOT NULL,
  set_at     timestamptz NOT NULL DEFAULT now()
);
