-- Почему подбор снял своё предложение. Группу временно убрали из подбора (вернули в «Потенциальную», поставили на паузу,
-- отметили «Не направлять») — предложения на неё снимаются, и автоподбор закрепляет людей за другими группами. Когда группу
-- открывают снова, закрепление за другими сильнее «новые группы первыми», и люди к ней не возвращались. Причина снятия
-- позволяет вернуть ровно их: 'unavailable' — группа перестала принимать людей, 'data' — изменились данные заявки,
-- 'replaced' — заменено по другой причине. Пусто — снято человеком («Подобрать заново», «Пересчитать все»), утверждением,
-- сменой пола или меткой «странный»: такие не возвращаются. Старые строки причины не знают и не возвращаются.
ALTER TABLE placement_proposals
  ADD COLUMN superseded_reason text CHECK (superseded_reason IN ('unavailable', 'data', 'replaced'));
