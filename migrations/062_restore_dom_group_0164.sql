-- Разовая дозаливка для ДГ-0164 (Доценко Артём, «Дам дом»). До миграции 061 её открыли, вернули в «Потенциальную» и
-- открыли снова: автоподбор успел поставить к ней людей, при возврате закрепил их за другими группами, а причину снятия
-- тогда не записывали — и после повторного открытия к ней никто не вернулся. Помечаем снятые подбором предложения на эту
-- группу как снятые из-за её недоступности: ближайший проход подбора вернёт людей к ней сам (правила возврата — 061:
-- не вместо поставленного вручную, только при тех же данных заявки и пока группа подходит человеку).
-- Снятые подбором — те, что сняты в одной транзакции с записью журнала «matching.run» (автоподбор или кнопка). Снятые
-- «Подобрать заново», «Пересчитать все», утверждением, сменой пола или меткой не трогаем: их снял человек.
UPDATE placement_proposals p
   SET superseded_reason = 'unavailable'
 WHERE p.group_id = 164
   AND p.status = 'superseded'
   AND p.superseded_reason IS NULL
   AND EXISTS (SELECT 1 FROM audit_log a WHERE a.action = 'matching.run' AND a.at = p.decided_at);
