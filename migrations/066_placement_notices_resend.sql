-- Повторная отправка ведущим. До исправления (#85, деплой закончился 2026-10-30 10:40 UTC) сообщение ведущему уходило без
-- ФИО, возраста и удобного времени человека — только с телефоном. Такие помечаются, и полный вход переотправляет их одной
-- кнопкой («Настройки → Подбор»): ведущему приходит то же сообщение с пометкой «отправляем повторно» и новыми кнопками.
ALTER TABLE placement_notices
  -- Это повторная отправка: текст начинается с извинения, остальное — как у обычного сообщения.
  ADD COLUMN resend boolean NOT NULL DEFAULT false,
  -- Ушло ведущему без ФИО; снимается, когда повтор поставлен в очередь (или стал не нужен).
  ADD COLUMN needs_fio_resend boolean NOT NULL DEFAULT false;

-- Граница по времени, а не по «пустому ФИО»: текст сообщения не хранится, а что ушло — решала старая выборка. Сообщения,
-- ушедшие в последние минуты перед перезапуском бота, могли уже быть с ФИО — повтор им не вредит (он так и подписан).
UPDATE placement_notices SET needs_fio_resend = true
 WHERE recipient = 'leader' AND status = 'sent' AND sent_at < '2026-10-30 10:40:07+00';
