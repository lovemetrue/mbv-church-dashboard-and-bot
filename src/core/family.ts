/**
 * Семейное положение: каноничный вариант из свободного текста, который написал человек боту или внёс координатор.
 *
 * Вариантов два — «холост / не замужем» и «женат / замужем»; всё, что не понять однозначно, — «не указано» (null).
 * Исходный текст при этом не теряется: он лежит рядом (`family_status`) и показывается подсказкой («женат, двое детей»).
 *
 * То же распознавание есть в базе — функция `family_kind_of` (миграция 070): по ней триггер раскладывает и новые ответы
 * бота, и правки старого дашборда, и слияние карточек, которые этот код не видит. Обе реализации проверяет одна
 * таблица примеров `FAMILY_CASES` (tests/family.spec.ts и tests/familyMigration.spec.ts): меняя правило здесь,
 * меняйте и SQL, иначе тест на расхождение упадёт.
 */
export type FamilyKind = 'single' | 'married';

export const FAMILY_KINDS: readonly FamilyKind[] = ['single', 'married'];

// Границы слова — вручную: `\b` в JS не считает кириллицу буквами.
const W = '(?<![а-яa-z])';
const E = '(?![а-яa-z])';

/** «Не женат», «не был женат», «не замужем», «не в браке» — сначала отрицания: внутри них есть слова «женат» и «замуж». */
const NEGATED = new RegExp(`${W}(не\\s+(был\\s+|была\\s+)?(женат[а-я]*|замужем|в\\s+браке)|без\\s+(мужа|жены|супруг[а-я]*))${E}`, 'g');
/** Не в браке: холост, одинок, свободен, разведён, вдова. */
const SINGLE = new RegExp(`${W}(холост[а-я]*|одинок[а-я]*|свободн[а-я]*|свободен|развед[а-я]*|развод[а-я]*|вдов[а-я]*)${E}`);
/** В браке: женат, замужем, в браке, супруг(а), муж, жена. */
const MARRIED = new RegExp(`${W}(женат[а-я]*|замужем|замужн[а-я]*|в\\s+браке|супруг[а-я]*|муж|мужа|мужем|жена|жены|женой|венчан[а-я]*)${E}`);

/** Вариант по тексту; null — пусто, непонятно или противоречиво («разведена, снова замужем»). */
export function familyKindOf(text: string | null | undefined): FamilyKind | null {
  const t = (text ?? '').toLowerCase().replace(/ё/g, 'е').replace(/\s+/g, ' ').trim();
  if (t === '') return null;
  const negated = NEGATED.test(t);
  NEGATED.lastIndex = 0;
  const rest = t.replace(NEGATED, ' ');
  const single = negated || SINGLE.test(rest);
  const married = MARRIED.test(rest);
  if (single === married) return null;
  return single ? 'single' : 'married';
}

