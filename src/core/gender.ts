/**
 * Пол человека по ФИО: мужчине не предлагают женскую группу, а женщине — мужскую (см. `exclusionReason`).
 *
 * Пол в анкете не спрашивается, поэтому его выводим из ФИО, а где не выходит — оставляем пустым и просим служителя
 * заполнить. Угадывать нельзя: ошибка отправит человека в чужую группу. Поэтому каждое слово ФИО голосует само по
 * себе (отчество, имя из словаря, окончание фамилии), и пол ставится, только если все голоса совпали. «Иванов Мария»
 * — противоречие, а не «большинство».
 *
 * ФИО в базе записаны в любом порядке («Мария Соколова», «Соколова Мария Петровна»), поэтому позицию слова не
 * учитываем.
 */
export type Gender = 'м' | 'ж';

const norm = (w: string): string => w.toLowerCase().replace(/ё/g, 'е');

/**
 * Имена, включая домашние формы — так люди часто пишут в боте. Двусмысленные («Саша», «Женя», «Валя», «Слава»,
 * «Шура») нарочно не включены: их решит служитель или модель.
 */
