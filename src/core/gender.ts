/** Голос одного слова; null — слово о поле ничего не говорит. */
function voteOf(word: string): Gender | null {
  const w = norm(word);
  if (w.length < 2) return null;
  // «оглы»/«кызы» — отчество у азербайджанских и тюркских имён, пишется отдельным словом.
  if (w === 'оглы' || w === 'улы') return 'м';
  if (w === 'кызы' || w === 'гызы') return 'ж';
  if (MALE.has(w)) return 'м';
  if (FEMALE.has(w)) return 'ж';
  // Женское отчество: «-вна», «-чна» (Ильинична). Фамилий с таким окончанием нет, голос надёжный.
  if (w.length > 4 && /(вна|чна)$/.test(w)) return 'ж';
  // Фамилии: «-ов», «-ев», «-ин», «-ский» мужские, «-ова», «-ева», «-ина», «-ская» женские. Короче пяти букв не
  // смотрим: «Лев», «Ким», «Нина» — имена или неоднозначные слова, их решает словарь или служитель.
  if (w.length >= 5) {
    if (/(ова|ева|ина|ына|ская|цкая)$/.test(w)) return 'ж';
    if (/(ов|ев|ин|ын|ский|цкий|ской|цкой)$/.test(w)) return 'м';
  }
  return null;
}

/**
 * Мужское отчество «-вич», «-ич» — голос слабый: белорусские и сербские фамилии на «-ович» («Карпович», «Бабич») бывают
 * и у женщин. Поэтому он учитывается, только когда других голосов нет и в ФИО три слова и больше (отчество есть).
 */
const isMalePatronymic = (word: string): boolean => {
  const w = norm(word);
  return w.length > 4 && /ич$/.test(w);
};

/** Слова ФИО: буквы, дефисная фамилия делится на части («Гончарова-Шевчук» голосует «Гончаровой»). */
const wordsOf = (fio: string): string[] => fio.split(/[\s-]+/).map((w) => w.replace(/[^\p{L}]/gu, '')).filter((w) => w.length > 0);

/** Пол по ФИО: все голосующие слова согласны — пол; голосов нет или они расходятся — null. */
export function genderFromFio(fio: string | null | undefined): Gender | null {
  return genderWithHints(fio, new Map());
}

/**
 * Слова, которые стоит показать модели, чтобы определить пол остальных: из ФИО, по которым правила пол не поняли,
 * — только слова без собственного голоса. Отдаются по одному и без связи друг с другом: модель видит «Саша», «Ким»,
 * а не «Саша Ким» — так до неё не доходит ни одно ФИО целиком (имена, как и в помощнике, наружу не уходят).
 */
export function unresolvedNameWords(fios: readonly (string | null)[]): string[] {
  const out = new Set<string>();
  for (const fio of fios) {
    if (!fio || genderFromFio(fio) !== null) continue;
    const words = wordsOf(fio);
    const votes = new Set(words.map(voteOf).filter(Boolean));
    if (votes.size > 1) continue; // противоречие правил модель не разрешит — решает служитель
    if (votes.size === 0 && words.length >= 3 && words.some(isMalePatronymic)) continue;
    for (const w of words) if (voteOf(w) === null && w.length >= 2) out.add(w[0]!.toUpperCase() + w.slice(1).toLowerCase());
  }
  return [...out].sort((a, b) => a.localeCompare(b, 'ru'));
}

/**
 * Пол по ФИО с подсказками модели для отдельных слов (`words`: слово в нижнем регистре → пол). Те же правила: все
 * голоса — и свои, и модели — должны совпасть.
 */
export function genderWithHints(fio: string | null | undefined, words: ReadonlyMap<string, Gender>): Gender | null {
  if (!fio) return null;
  const all = wordsOf(fio);
  const votes = new Set<Gender>();
  for (const w of all) {
    const v = voteOf(w) ?? words.get(norm(w)) ?? null;
    if (v) votes.add(v);
  }
  if (votes.size === 0 && all.length >= 3 && all.some(isMalePatronymic)) return 'м';
  return votes.size === 1 ? [...votes][0]! : null;
}
