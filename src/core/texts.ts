const cb = (text: string, data: string): Button => ({ kind: 'callback', text, data });

export const consentKeyboard = (): Button[][] => [
  [cb(BTN.consentYes, CB.consentYes)],
  [cb(BTN.consentNo, CB.consentNo)],
];

/** Кнопки вариантов церкви: данные передаём индексом, список настраивается в .env. */
export const churchKeyboard = (): Button[][] =>
  churchOptions().map((label, index) => [cb(label, `${CB.churchPrefix}${index}`)]);

export const mdgKeyboard = (): Button[][] => [
  [cb(BTN.mdgOpen, CB.mdgOpen)],
  [cb(BTN.mdgJoin, CB.mdgJoin)],
  [cb(BTN.mdgMember, CB.mdgMember)],
  [cb(BTN.mdgLeader, CB.mdgLeader)],
];

/** Кнопка досрочного завершения: показывается на уточняющих вопросах. */
export const finishKeyboard = (extra: Button[][] = []): Button[][] => [
  ...extra,
  [cb(BTN.finishEarly, CB.finishEarly)],
];

export const skipKeyboard = (): Button[][] => finishKeyboard([[cb(BTN.skip, CB.skip)]]);

export const summaryKeyboard = (): Button[][] => [
  [cb(BTN.confirm, CB.confirm)],
  [cb(BTN.redo, CB.redo)],
];

/** Меню участника. Пункт «Дозаполнить анкету» появляется, если регистрация неполная. */
/** Единственная кнопка на шаге вопроса: передумать можно в любой момент. */
export const cancelQuestionKeyboard = (): Button[][] => [[cb(BTN.cancelQuestion, CB.cancelQuestion)]];

export const menuKeyboard = (incomplete = false): Button[][] => {
  const rows = [
    [cb(BTN.menuAsk, CB.menuAsk)],
    [cb(BTN.menuStatus, CB.menuStatus)],
    [cb(BTN.menuLead, CB.menuLead)],
  ];
  if (incomplete) rows.unshift([cb(BTN.menuResume, CB.menuResume)]);
  return rows;
};
