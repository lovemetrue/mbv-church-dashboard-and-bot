/**
 * «Вернуться» на уточняющих вопросах: человек мог нажать не ту кнопку в вопросе
 * про малую группу, и без этого ему пришлось бы заполнять анкету заново.
 */
export const backKeyboard = (): Button[][] => [[cb(BTN.back, CB.back)]];

/**
 * Сводка: подтвердить, переписать анкету заново или вернуться к выбору про малую группу.
 *
 * «Вернуться» нужна и здесь: у ведущего уточняющих вопросов нет, он попадает на сводку
 * сразу, и без этой кнопки исправить случайное нажатие можно было только «Заполнить
 * заново» — то есть с ФИО. Обязательные ответы «Вернуться» не стирает.
 */
export const summaryKeyboard = (): Button[][] => [
  [cb(BTN.confirm, CB.confirm)],
  [cb(BTN.redo, CB.redo)],
  [cb(BTN.back, CB.back)],
];

/** Единственная кнопка на шаге вопроса: передумать можно в любой момент. */
export const cancelQuestionKeyboard = (): Button[][] => [[cb(BTN.cancelQuestion, CB.cancelQuestion)]];

