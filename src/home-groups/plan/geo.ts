function buildNeighbors(): Record<string, string[]> {
  const result: Record<string, string[]> = {};
  // Все районы справочника получают запись, даже пустую: «неизвестно» и «нет соседей» для
  // движка одно и то же, но тесту нужно видеть, что район не забыт.
  for (const district of DISTRICTS) result[district] = [];
  for (const [a, b] of NEIGHBOR_PAIRS) {
    (result[a] ??= []).push(b);
    (result[b] ??= []).push(a);
  }
  for (const list of Object.values(result)) list.sort((x, y) => x.localeCompare(y, 'ru'));
  return result;
}

