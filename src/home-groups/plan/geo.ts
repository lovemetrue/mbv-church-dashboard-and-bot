/** Слова, которые пишут перед названием станции и которые станцию не определяют. */
const STATION_NOISE = new Set(['м', 'ст', 'стм', 'метро', 'станция', 'станции']);

/**
 * Ключ станции в индексах: нижний регистр, «е» вместо «ё», без «м.», «метро», «ст.м.», знаков
 * препинания и лишних пробелов. Так «Ст.м.Улица Дыбенко» и «улица дыбенко» — одна станция.
 */
export function normalizeStation(name: string): string {
  return name
    .toLowerCase()
    .replaceAll('ё', 'е')
    .replace(/[^\p{L}\p{N}\s-]/gu, ' ')
    .split(/\s+/)
    .filter((word) => word && !STATION_NOISE.has(word))
    .join(' ');
}

const STATIC_INDEX: ReadonlyMap<string, string> = new Map(
  Object.entries(METRO_DISTRICT).map(([station, district]) => [normalizeStation(station), district]),
);

/** Реальные районы города и области: у «Онлайн» и «Не указан» метро — не география. */
const GEOGRAPHIC_DISTRICTS: ReadonlySet<string> = new Set(DISTRICTS.filter((d) => d !== 'Онлайн'));

/**
 * Станция → район по самим группам реестра. В индекс попадает станция, которую встретили у
 * групп ровно одного района: если районов несколько, мы не знаем, чему верить (так в таблице
 * Девяткино — то Красногвардейский, то область), и лучше промолчать, чем ошибиться.
 * Группы «Онлайн» и «Не указан» пропускаем: в их колонке «метро» стоят «Финляндия» или
 * «Санкт-Петербург», и заявка «Санкт-Петербург» не должна превращаться в онлайн-группу.
 */
export function buildMetroIndex(groups: readonly { metro: string | null; district: string }[]): Map<string, string> {
  const seen = new Map<string, Set<string>>();
  for (const group of groups) {
    if (!group.metro || !GEOGRAPHIC_DISTRICTS.has(group.district)) continue;
    for (const part of group.metro.split(/[,;/]/)) {
      const key = normalizeStation(part);
      if (!key) continue;
      const districts = seen.get(key) ?? new Set<string>();
      districts.add(group.district);
      seen.set(key, districts);
    }
  }
  const index = new Map<string, string>();
  for (const [key, districts] of seen) {
    if (districts.size === 1) index.set(key, [...districts][0]!);
  }
  return index;
}

// ── разбор места ────────────────────────────────────────────────────────────

/** Места в одной строке разделены запятой, «/», точкой с запятой, скобками или «или»: «Кудрово (Дыбенко)». */
const PLACE_SEPARATOR = /[,;/()]|\s(?:или|либо)\s/;

/**
 * Станция из списка, названная в куске текста. Если подходит несколько, берём с самым длинным
 * названием: «Пушкинская» подходит и под «Пушкин», но она точнее. При равной длине — по алфавиту,
 * чтобы результат не зависел от порядка добавления в карту.
 */
function stationDistrict(segment: string, stations: ReadonlyMap<string, string>): string | null {
  let best: string | null = null;
  for (const station of stations.keys()) {
    if (!matchesMetro(segment, station)) continue;
    if (best === null || station.length > best.length || (station.length === best.length && station < best)) {
      best = station;
    }
  }
  return best === null ? null : (stations.get(best) ?? null);
}

/**
 * Район по свободному тексту места («Приморский, м. Пионерская», «где-то у Озерков»). Для каждого
 * из перечисленных мест по порядку: сначала район, названный словами, затем станция (сперва из
 * индекса групп, потом из справочника). Берём первое распознанное. Не распозналось — null:
 * заявка уйдёт человеку на уточнение, а не к случайной группе.
 */
export function resolveDistrict(place: string | null, metroIndex?: ReadonlyMap<string, string>): string | null {
  if (!place) return null;
  for (const segment of place.split(PLACE_SEPARATOR)) {
    if (!segment.trim()) continue;
    const named = DISTRICTS.find((district) => matchesDistrict(segment, district));
    if (named) return named;
    const fromGroups = metroIndex ? stationDistrict(segment, metroIndex) : null;
    if (fromGroups) return fromGroups;
    const fromReference = stationDistrict(segment, STATIC_INDEX);
    if (fromReference) return fromReference;
  }
  return null;
}
