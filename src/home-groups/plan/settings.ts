import { NEIGHBORS } from './geo.js';
import type { PlanSettings } from './types.js';

/**
 * Вес района — и ровно такой же вес дня недели. Одна константа, а не два числа: так «день весит как район» не
 * разойдётся, если кто-то поправит один из весов. Район важнее всего: человек не поедет через полгорода; а группа
 * в другой день — это группа, в которую он не придёт.
 */
export const DISTRICT_WEIGHT = 40;

/**
 * Настройки подбора по умолчанию. Веса и пороги живут здесь, а не в коде движка: служитель
 * должен иметь возможность объяснить, почему группа получила столько-то очков, и церковь
 * может менять веса, не трогая логику.
 */
export const DEFAULT_SETTINGS: PlanSettings = {
  // Район и день недели весят одинаково (`DISTRICT_WEIGHT`). Возраст — следующий по весу: группа «не по возрасту»
  // отсеивается и так, а вес различает «точно по возрасту» и «с краю». Время суток — прежние 20 очков, что раньше
  // делили день и время вместе: день недели теперь считается отдельно и весомо.
  weights: { district: DISTRICT_WEIGHT, day: DISTRICT_WEIGHT, age: 25, slot: 20, street: 15 },
  defaultCapacity: 10,
  humanThreshold: 60,
  staleDays: 30,
  stalePenalty: 5,
  lastSeatPenalty: 3,
  confidenceFloor: 0.55,
  confidenceSpan: 0.45,
  neighbors: NEIGHBORS,
};
