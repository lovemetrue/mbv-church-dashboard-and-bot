/**
 * Улица из свободного текста: «ул. Рылеева, д. 32, кв. 5», «Комендантский пр. 10к2», «Рылеева 32». Человек в боте пишет
 * улицу и дом одной строкой, а подбору нужна только улица: «Рылеева 32» и «ул. Рылеева, 34» — одна улица.
 * Разбор честный: если улицу выделить нельзя (написали метро, район или пусто), ответ — null, а не догадка.
 */

/**
 * Типы улиц, которые не отличают одну улицу от другой: «Комендантский пр.», «Комендантский проспект» и «Комендантского
 * проспекта». Падежи перечислены основой, чтобы не потерять «улицы», «проспекта», «набережной».
 */
const STREET_TYPE = /^(?:ул|улиц\p{L}*|пр|просп|проспект\p{L}*|пр-т|пр-кт|пер|переул\p{L}+|наб|набережн\p{L}+|б-р|бул|бульвар\p{L}*|ш|шоссе|пл|площад\p{L}+|аллея|аллеи|дорог\p{L}+|линия|линии|пр-д|проезд\p{L}*|тупик\p{L}*|г|город\p{L}*|спб|санкт-петербург\p{L}*)$/u;

/** Слова, после которых идёт номер дома, корпуса или квартиры: дальше улицы уже нет. */
const HOUSE_MARKERS = new Set([
  'д', 'дом', 'к', 'корп', 'корпус', 'стр', 'строение', 'кв', 'квартира', 'лит', 'литера', 'подъезд', 'эт', 'этаж',
]);

/** Точка тоже разделитель: «ул.Рылеева» и «д.32» пишут слитно. */
const words = (text: string): string[] =>
  text.toLowerCase().replaceAll('ё', 'е').replace(/[,;.()«»"]/g, ' ').split(/\s+/).filter(Boolean);

/** Слово названия с цифрой — порядковое («5-я Советская», «1-я линия»), а не номер дома. */
const isOrdinal = (word: string): boolean => /^\d{1,2}-?(?:я|й|е|ая|ой|ый|ое|ья)$/.test(word);
const hasDigit = (word: string): boolean => /\d/.test(word);

/**
 * Основа слова без падежного окончания: «Рылеева» и «Рылеевой», «Комендантский» и «Комендантского» сходятся, а
 * «Ленина» и «Ленинский» — нет (разные улицы). Слишком короткое слово не режем.
 */
const ENDINGS = /(?:ого|его|ому|ему|ий|ый|ой|ая|яя|ое|ее|ом|ем|ую|юю|ых|их|ым|им|а|я|у|ю|е|ы|и|ь|й|о)$/;
const stem = (word: string): string => {
  const cut = word.replace(ENDINGS, '');
  return cut.length >= 3 ? cut : word;
};

/**
 * Название улицы без типа и без дома. Берём слова до первого номера или слова «дом»/«кв» и выбрасываем «ул.», «пр.».
 * Слова упорядочиваются, чтобы «пр. Комендантский» и «Комендантский пр.» дали один ключ.
 */
export function streetName(raw: string | null | undefined): string | null {
  const kept: string[] = [];
  for (const word of words(raw ?? '')) {
    if (HOUSE_MARKERS.has(word) && kept.length > 0) break;
    if (hasDigit(word) && !isOrdinal(word)) {
      // Номер перед названием («32 Рылеева») пропускаем, номер после — конец улицы.
      if (kept.length === 0) continue;
      break;
    }
    if (STREET_TYPE.test(word) || HOUSE_MARKERS.has(word)) continue;
    kept.push(word.replace(/[^\p{L}\p{N}-]+/gu, ''));
  }
  const name = kept.filter(Boolean);
  return name.length > 0 ? name.join(' ') : null;
}

/** Ключ для сравнения улиц: без типа, дома и падежа, слова по алфавиту. null — улицу выделить не удалось. */
export function streetKey(raw: string | null | undefined): string | null {
  const name = streetName(raw);
  if (name === null) return null;
  const key = name.split(' ').map(stem).sort().join(' ');
  return key === '' ? null : key;
}
