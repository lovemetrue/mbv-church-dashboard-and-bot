import type { MailMessage } from './mailer.js';

/**
 * Тексты писем. Обычный текст без вёрстки: так письмо не режет почтовый фильтр и оно читается
 * везде. Без местоимений, зависящих от пола, и без личных данных кроме имени получателя.
 */

export function inviteMail(to: string, fullName: string, login: string, link: string, days: number): MailMessage {
  return {
    to,
    subject: 'Домашние группы: задайте пароль',
    text: [
      `Здравствуйте, ${fullName}!`,
      '',
      'Для вас заведён личный вход в сервис «Домашние группы» церкви «Миссия Благая Весть».',
      `Ваш логин: ${login}`,
      '',
      'Пароль вы задаёте сами. Откройте ссылку и придумайте пароль (не короче 10 знаков):',
      link,
      '',
      `Ссылка одноразовая и действует ${days} дн. Если она устарела, попросите администратора выслать новую.`,
      'Если вы не ожидали это письмо, просто проигнорируйте его.',
    ].join('\n'),
  };
}

export function resetMail(to: string, fullName: string, login: string, link: string, hours: number): MailMessage {
  return {
    to,
    subject: 'Домашние группы: смена пароля',
    text: [
      `Здравствуйте, ${fullName}!`,
      '',
      'Для вашего входа в сервис «Домашние группы» запрошена смена пароля.',
      `Ваш логин: ${login}`,
      '',
      'Чтобы задать новый пароль, откройте ссылку:',
      link,
      '',
      `Ссылка одноразовая и действует ${hours} ч. Старый пароль перестанет работать после смены, а все прежние входы закроются.`,
      'Если вы не запрашивали смену пароля, ничего не делайте: пароль останется прежним. Сообщите администратору, если такие письма приходят без вашего запроса.',
    ].join('\n'),
  };
}
