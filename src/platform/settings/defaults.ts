export const findBlock = (agent: string, block: string): { agent: AgentDefault; block: BlockDefault } | null => {
  const a = AGENTS.find((x) => x.key === agent);
  const b = a?.blocks.find((x) => x.key === block);
  return a && b ? { agent: a, block: b } : null;
};
