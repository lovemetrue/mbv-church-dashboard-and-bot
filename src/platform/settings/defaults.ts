export interface BlockDefault {
  key: BlockKey;
  title: string;
  purpose: string;
  editable: boolean;
  text: string;
}

export interface AgentDefault {
  key: AgentKey;
  title: string;
  model: string;
  blocks: BlockDefault[];
}

