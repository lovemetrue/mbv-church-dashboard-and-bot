/**
 * Вырезает из текста то, что похоже на телефон или почту. Журнал ошибок читают администраторы,
 * а в тексте ошибки легко оказывается кусок запроса или строки базы; персональные данные там
 * не нужны и храниться не должны.
 */
const EMAIL = /[\p{L}\p{N}._%+-]+@[\p{L}\p{N}.-]+\.[\p{L}]{2,}/gu;
// Цепочка из 10+ цифр с пробелами, скобками и дефисами между ними: «+7 (999) 123-45-67», «89991234567».
const PHONE = /(?<![\d])\+?\d[\d\s().-]{8,}\d(?![\d])/g;

export const HIDDEN = '[скрыто]';

export function redactPersonal(text: string): string {
  return text
    .replace(EMAIL, HIDDEN)
    .replace(PHONE, (m) => (m.replace(/\D/g, '').length >= 10 ? HIDDEN : m));
}
