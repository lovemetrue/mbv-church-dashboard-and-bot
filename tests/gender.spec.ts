import { describe, expect, test } from 'vitest';
import { genderFromFio, unresolvedNameWords } from '../src/core/gender.js';

describe('пол по ФИО', () => {
  test.each([
    ['Иванов Иван Иванович', 'м'],
    ['Мария Соколова', 'ж'],
    ['Соколова Мария Петровна', 'ж'],
    ['Алексей Орлов', 'м'],
    ['Никита Белов', 'м'],
    ['Илья', 'м'],
    ['Петрова', 'ж'],
    ['Кузнецова Ольга', 'ж'],
    ['Семёнов Пётр', 'м'],
    ['Семенова', 'ж'],
    ['Мамедов Эльдар оглы', 'м'],
    ['Алиева Лейла кызы', 'ж'],
    ['Достоевский Фёдор', 'м'],
    ['Гончарова-Шевчук Анна', 'ж'],
    ['маша', 'ж'],
    ['ДИМА', 'м'],
    ['Карпович Мария Ивановна', 'ж'],
    ['Бабич Тагир Ильдарович', 'м'],
    ['Шевчук Остап Ильич', 'м'],
  ])('«%s» — %s', (fio, want) => {
    expect(genderFromFio(fio)).toBe(want);
  });

  test.each([
    ['Саша Ким'],
    ['Женя'],
    ['Ким Чен'],
    ['Шевчук'],
    // фамилия на «-ович» бывает и у женщин: без отчества пол по ней не ставим
    ['Карпович'],
    ['Карпович Саша'],
    [''],
    [null],
    // противоречие: мужская фамилия и женское имя — не угадываем, а просим заполнить
    ['Иванов Мария'],
  ])('«%s» — пол не понять, остаётся пустым', (fio) => {
    expect(genderFromFio(fio)).toBeNull();
  });

  test('слова, по которым пол не понять, отдаются по одному, без повторов и без понятых имён', () => {
    expect(unresolvedNameWords(['Саша Ким', 'Женя Ким', 'Мария Петрова', 'Шевчук Ярослав'])).toEqual(['Женя', 'Ким', 'Саша']);
  });
});
