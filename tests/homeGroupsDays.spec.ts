import { describe, expect, test } from 'vitest';
import { classifyDays } from '../src/home-groups/plan/days.js';
import { buildPlan } from '../src/home-groups/plan/engine.js';
import { parseGroupWhen, parseHumanSchedule } from '../src/home-groups/plan/parse.js';
import { DEFAULT_SETTINGS } from '../src/home-groups/plan/settings.js';
import type { PlanEntryProposal, PlanGroup, PlanRequest } from '../src/home-groups/plan/types.js';

/**
 * Классификация дней недели из свободного текста — единственный разбор дней в подборе: им читаются и «удобное время»
 * человека, и колонка «день» группы. Скрипт делает это сам, чтобы нейросеть не тратили на «ср» и «в пятницу».
 */
const days = (text: string) => classifyDays(text).days;

describe('один день: сокращения, названия и падежи', () => {
  test.each([
    ['пн', ['Пн']], ['Пн.', ['Пн']], ['пон', ['Пн']], ['понед.', ['Пн']],
    ['понедельник', ['Пн']], ['в понедельник', ['Пн']], ['по понедельникам', ['Пн']], ['с понедельника', ['Пн']],
    ['вт', ['Вт']], ['втр', ['Вт']], ['вторник', ['Вт']], ['во вторник', ['Вт']], ['по вторникам', ['Вт']], ['вторниками', ['Вт']],
    ['ср', ['Ср']], ['срд', ['Ср']], ['среда', ['Ср']], ['в среду', ['Ср']], ['по средам', ['Ср']], ['средой', ['Ср']], ['в среде', ['Ср']],
    ['чт', ['Чт']], ['чтв', ['Чт']], ['четв.', ['Чт']], ['четверг', ['Чт']], ['в четверг', ['Чт']], ['по четвергам', ['Чт']],
    ['пт', ['Пт']], ['птн', ['Пт']], ['пятн.', ['Пт']], ['пятница', ['Пт']], ['в пятницу', ['Пт']], ['по пятницам', ['Пт']], ['пятницей', ['Пт']],
    ['сб', ['Сб']], ['суб', ['Сб']], ['субб.', ['Сб']], ['суббота', ['Сб']], ['в субботу', ['Сб']], ['по субботам', ['Сб']],
    ['вс', ['Вс']], ['вск', ['Вс']], ['воскр.', ['Вс']], ['воскресенье', ['Вс']], ['в воскресенье', ['Вс']], ['по воскресеньям', ['Вс']],
    ['СРЕДА', ['Ср']], ['Пятница, вечер', ['Пт']], ['ср19:00', ['Ср']], ['(чт)', ['Чт']],
  ])('«%s» → %j', (text, expected) => {
    expect(days(text)).toEqual(expected);
  });
});

describe('несколько дней: списки, «и», «или», слэш', () => {
  test.each([
    ['вт и чт', ['Вт', 'Чт']],
    ['вт, чт', ['Вт', 'Чт']],
    ['вт или чт', ['Вт', 'Чт']],
    ['по вторникам и четвергам', ['Вт', 'Чт']],
    ['среда/пятница', ['Ср', 'Пт']],
    ['сб/вс', ['Сб', 'Вс']],
    ['сб,вс', ['Сб', 'Вс']],
    ['в субботу или воскресенье', ['Сб', 'Вс']],
    ['ср, пн, среда, понедельник', ['Пн', 'Ср']],
    ['пн-ср-пт', ['Пн', 'Ср', 'Пт']],
    ['пн/ср/пт', ['Пн', 'Ср', 'Пт']],
  ])('«%s» → %j', (text, expected) => {
    expect(days(text)).toEqual(expected);
  });

  test('«сб/вс» и «пн-ср-пт» — перечисления, а не диапазоны: промежуточных дней не прибавляется', () => {
    expect(days('пн-ср-пт')).not.toContain('Вт');
    expect(days('пт/пн')).toEqual(['Пн', 'Пт']);
  });
});

describe('диапазоны', () => {
  test.each([
    ['пн-ср', ['Пн', 'Вт', 'Ср']],
    ['пн - пт', ['Пн', 'Вт', 'Ср', 'Чт', 'Пт']],
    ['пн–пт', ['Пн', 'Вт', 'Ср', 'Чт', 'Пт']],
    ['пн—чт', ['Пн', 'Вт', 'Ср', 'Чт']],
    ['с понедельника по среду', ['Пн', 'Вт', 'Ср']],
    ['с пн по пт', ['Пн', 'Вт', 'Ср', 'Чт', 'Пт']],
    ['с пн до ср', ['Пн', 'Вт', 'Ср']],
    ['пт-пн', ['Пн', 'Пт', 'Сб', 'Вс']],
    ['пятница-воскресенье', ['Пт', 'Сб', 'Вс']],
  ])('«%s» → %j', (text, expected) => {
    expect(days(text)).toEqual(expected);
  });

  test('«по» без «с» диапазона не делает: «пн по ср» — названы два дня, а не вся неделя между ними', () => {
    expect(days('пн по ср')).toEqual(['Пн', 'Ср']);
  });
});

describe('группы дней и «любой день»', () => {
  test.each([
    ['будни', ['Пн', 'Вт', 'Ср', 'Чт', 'Пт']],
    ['в будни', ['Пн', 'Вт', 'Ср', 'Чт', 'Пт']],
    ['по будням', ['Пн', 'Вт', 'Ср', 'Чт', 'Пт']],
    ['в будние дни', ['Пн', 'Вт', 'Ср', 'Чт', 'Пт']],
    ['выходные', ['Сб', 'Вс']],
    ['на выходных', ['Сб', 'Вс']],
    ['по выходным', ['Сб', 'Вс']],
    ['уикенд', ['Сб', 'Вс']],
    ['будни или суббота', ['Пн', 'Вт', 'Ср', 'Чт', 'Пт', 'Сб']],
  ])('«%s» → %j', (text, expected) => {
    expect(days(text)).toEqual(expected);
  });

  test.each(['любой день', 'в любой день', 'каждый день', 'в любое время', 'ежедневно', 'не важно', 'как получится', ''])(
    '«%s» — ограничения по дням нет',
    (text) => {
      expect(classifyDays(text)).toEqual({ days: [], avoid: [] });
    },
  );
});

describe('ложные срабатывания: сокращение внутри другого слова днём не считается', () => {
  test.each([
    'средний', 'в среднем', 'среди недели', 'средства', 'средняя группа',
    'все', 'всё', 'всегда', 'всем удобно', 'всякий раз', 'вселенная',
    'пять', 'пятно', 'пятёрка', 'пятый',
    'второй', 'вторично', 'четвёртый', 'четверть', 'что', 'чтобы',
    'суббо', 'субтитры', 'сбор', 'сбоку', 'понятно', 'понимаю', 'понедельно',
    'воскрес', 'вскоре', 'птица', 'вторжение',
  ])('«%s» → дней нет', (text) => {
    expect(days(text)).toEqual([]);
  });

  test('цифры и знаки рядом не мешают: «19:00 ср.» — среда', () => {
    expect(days('19:00 ср.')).toEqual(['Ср']);
  });
});

describe('нежелательные дни: «кроме», «не»', () => {
  test.each([
    ['кроме воскресенья', [], ['Вс']],
    ['кроме вс', [], ['Вс']],
    ['не по средам', [], ['Ср']],
    ['не в пятницу', [], ['Пт']],
    ['не могу в пятницу', [], ['Пт']],
    ['только не вторник', [], ['Вт']],
    ['вторник не могу', [], ['Вт']],
    ['вт, чт не получится', [], ['Вт', 'Чт']],
    ['кроме выходных', [], ['Сб', 'Вс']],
    ['кроме пн и вт', [], ['Пн', 'Вт']],
    ['пн-пт, кроме среды', ['Пн', 'Вт', 'Чт', 'Пт'], ['Ср']],
    ['вт не могу, но чт можно', ['Чт'], ['Вт']],
    ['в пн могу, вт не могу', ['Пн'], ['Вт']],
  ])('«%s» → дни %j, не подходят %j', (text, wanted, avoid) => {
    expect(classifyDays(text)).toEqual({ days: wanted, avoid });
  });

  test('«не» без дня после него (время, слова) дни не отменяет', () => {
    expect(classifyDays('вт, не раньше 18')).toEqual({ days: ['Вт'], avoid: [] });
    expect(classifyDays('пн и ср не позже 21')).toEqual({ days: ['Пн', 'Ср'], avoid: [] });
    expect(classifyDays('не знаю, чт')).toEqual({ days: ['Чт'], avoid: [] });
  });

  test('отрицание обрывается словом «но»: в «кроме вс, но пн можно» пн всё же подходит; а «кроме вс, пн» отменяет оба', () => {
    expect(classifyDays('кроме вс, но пн можно')).toEqual({ days: ['Пн'], avoid: ['Вс'] });
    expect(classifyDays('кроме вс, пн')).toEqual({ days: [], avoid: ['Пн', 'Вс'] });
  });
});

describe('удобное время человека целиком (дни + время суток)', () => {
  test.each([
    ['ср вечером', ['Ср'], 'вечер'],
    ['по пятницам после работы', ['Пт'], 'вечер'],
    ['сб/вс утром', ['Сб', 'Вс'], 'утро'],
    ['пн-ср с 18 до 21', ['Пн', 'Вт', 'Ср'], 'вечер'],
    ['в обеденное время по будням', ['Пн', 'Вт', 'Ср', 'Чт', 'Пт'], 'день'],
    ['вт в обед', ['Вт'], 'день'],
    ['вс до обеда', ['Вс'], 'утро'],
    ['вс после обеда', ['Вс'], 'день'],
    ['чт не раньше 18', ['Чт'], 'вечер'],
  ])('«%s» → %j, %s', (text, expectedDays, slot) => {
    const w = parseHumanSchedule(text);
    expect(w.days).toEqual(expectedDays);
    expect(w.slot).toBe(slot);
  });

  test('«рабочий день», «каждый день», «будний день» временем суток «день» не считаются', () => {
    for (const text of ['рабочий день', 'каждый день', 'будний день', 'любой день', 'весь день', 'один день']) {
      expect(parseHumanSchedule(text).slot, text).toBeNull();
    }
  });

  test('«днём» и «днем» — это время суток, а «в течение дня» — нет', () => {
    expect(parseHumanSchedule('в субботу днем').slot).toBe('день');
    expect(parseHumanSchedule('в субботу днём').slot).toBe('день');
    expect(parseHumanSchedule('вс в течение дня').slot).toBeNull();
  });

  test('нежелательное время суток уходит в avoidSlots и временем человека не становится', () => {
    expect(parseHumanSchedule('не утром')).toMatchObject({ slot: null, avoidSlots: ['утро'] });
    expect(parseHumanSchedule('кроме вечера')).toMatchObject({ slot: null, avoidSlots: ['вечер'] });
    expect(parseHumanSchedule('пн, не по утрам, лучше вечером')).toMatchObject({ days: ['Пн'], slot: 'вечер', avoidSlots: ['утро'] });
  });

  test('нежелательные дни возвращаются как avoidDays, а в days их нет', () => {
    expect(parseHumanSchedule('кроме воскресенья, вечером')).toEqual({ days: [], slot: 'вечер', avoidDays: ['Вс'], avoidSlots: [] });
  });
});

describe('день и время группы читаются тем же разбором, что и у человека', () => {
  test.each([
    ['Ср', 'Ср'], ['ср', 'Ср'], ['Среда', 'Ср'], ['среду', 'Ср'], ['Пт.', 'Пт'], ['пятница (раз в две недели)', 'Пт'],
    ['каждый вторник', 'Вт'], ['по четвергам', 'Чт'], ['Воскр.', 'Вс'], ['вс', 'Вс'],
  ])('день группы «%s» → %s', (raw, day) => {
    expect(parseGroupWhen(raw, null).day).toBe(day);
  });

  test.each(['Среда, Четверг', 'вт/чт', 'Будни', 'Выходные', 'пн-ср', 'Плавающий', 'None', '', 'кроме воскресенья'])(
    'несколько дней, диапазон, отрицание или «плавающий» («%s») — день группы неизвестен',
    (raw) => {
      expect(parseGroupWhen(raw, null).day).toBeNull();
    },
  );

  test.each([
    ['19:00', 'вечер'], ['19.30', 'вечер'], ['9:00', 'утро'], ['13:00', 'день'], ['Вечер', 'вечер'], ['День', 'день'], ['утро', 'утро'],
    ['19:00-21:00', 'вечер'], ['с 19:00', 'вечер'], ['в 19:00', 'вечер'], ['10:00–12:00', 'утро'], ['вечером', 'вечер'],
  ])('время группы «%s» → %s', (raw, slot) => {
    expect(parseGroupWhen('Вт', raw).slot).toBe(slot);
  });

  test('время суток, записанное прямо в колонке «день» («Среда 19:00»), берётся, если колонка времени пуста', () => {
    expect(parseGroupWhen('Среда 19:00', null)).toEqual({ day: 'Ср', slot: 'вечер' });
    expect(parseGroupWhen('Среда 19:00', '10:00')).toEqual({ day: 'Ср', slot: 'утро' });
  });

  test('«Плавающий» и пустое время суток не дают', () => {
    expect(parseGroupWhen('Вт', 'Плавающий').slot).toBeNull();
    expect(parseGroupWhen('Вт', '').slot).toBeNull();
    expect(parseGroupWhen('Вт', null).slot).toBeNull();
  });
});

describe('от текста до группы: подбор выбирает группу в нужный день', () => {
  const groupOf = (id: number, day: string, time: string): PlanGroup => ({
    id, no: id, leader: 'Ведущий', district: 'Приморский', metro: null, ageRange: null, ...parseGroupWhen(day, time),
    street: null, people: 3, capacity: 10, status: 'Функционирует', acceptsNew: true, doNotRefer: false, verifiedDaysAgo: 3,
  });
  const requestOf = (schedule: string): PlanRequest => ({
    id: 1, fio: 'Человек', ageRange: null, district: 'Приморский', place: null, street: null, rejectedGroupIds: [],
    pinnedGroupId: null, waitingDays: 1, ...parseHumanSchedule(schedule),
  });
  const groups = [groupOf(1, 'Пн', '19:00'), groupOf(2, 'Среда', '19:00'), groupOf(3, 'пт', 'вечер'), groupOf(4, 'Вс', '11:00')];
  const chosen = (schedule: string): number => {
    const entry = buildPlan({ requests: [requestOf(schedule)], groups, settings: DEFAULT_SETTINGS }).entries.get(1);
    expect(entry?.kind).toBe('proposal');
    return (entry as PlanEntryProposal).main.groupId;
  };

  test.each([
    ['ср', 2], ['в пятницу', 3], ['по пн', 1], ['воскр.', 4], ['сб/вс', 4], ['пн-ср', 1], ['вт и пт', 3],
  ])('«%s» → группа %i', (schedule, id) => {
    expect(chosen(schedule)).toBe(id);
  });

  test('день решает сильнее времени суток: в нужный день утром лучше, чем в другой день вечером', () => {
    expect(chosen('вс вечером')).toBe(4);
  });

  test('«кроме» исключает группы этого дня совсем', () => {
    const entry = buildPlan({ requests: [requestOf('кроме понедельника, вторника, среды, пятницы')], groups, settings: DEFAULT_SETTINGS }).entries.get(1);
    expect((entry as PlanEntryProposal).main.groupId).toBe(4);
  });
});
