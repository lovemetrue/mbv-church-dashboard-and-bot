import { describe, expect, test } from 'vitest';
import { streetKey, streetName } from '../src/home-groups/plan/street.js';

/**
 * Улица из того, что человек написал в боте («Улица и дом» одной строкой). Подбору нужна только улица: дом, корпус и
 * квартира её не отличают, а тип («ул.», «проспект») и падеж — тоже.
 */
describe('название улицы без дома и типа', () => {
  test.each([
    ['ул. Рылеева, д. 32, кв. 5', 'рылеева'],
    ['Рылеева 32', 'рылеева'],
    ['улица Рылеева', 'рылеева'],
    ['ул.Рылеева д.32', 'рылеева'],
    ['32 Рылеева', 'рылеева'],
    ['Комендантский пр. 10к2', 'комендантский'],
    ['пр-т Комендантский, 10 корп. 2', 'комендантский'],
    ['Невский проспект, дом 100', 'невский'],
    ['ул. Рылеева, дом А', 'рылеева'],
    ['Рылеева лит. Б', 'рылеева'],
    ['г. Санкт-Петербург, Литейный пр., 12', 'литейный'],
    ['5-я Советская ул., 3', '5-я советская'],
    ['Старая Деревня, ул. Дибуновская 11', 'старая деревня дибуновская'],
  ])('«%s» → %s', (raw, expected) => {
    expect(streetName(raw)).toBe(expected);
  });

  test.each([null, undefined, '', '   ', 'д. 5', '32', 'кв. 12', 'ул.'])('«%s» → улицу выделить нельзя', (raw) => {
    expect(streetName(raw)).toBeNull();
    expect(streetKey(raw)).toBeNull();
  });
});

describe('ключ для сравнения улиц', () => {
  test.each([
    ['Комендантский пр.', 'комендантский проспект'],
    ['пр. Комендантский', 'Комендантский проспект, 10'],
    ['Рылеева', 'ул. Рылеевой, 5'],
    ['Невский пр.', 'Невского проспекта 100'],
    ['ул. Ленина', 'Ленина улица'],
    ['ёлочная', 'Елочная ул.'],
  ])('«%s» и «%s» — одна улица', (a, b) => {
    expect(streetKey(a)).toBe(streetKey(b));
    expect(streetKey(a)).not.toBeNull();
  });

  test.each([
    ['ул. Ленина', 'Ленинский пр.'],
    ['Рылеева', 'Рубинштейна'],
    ['1-я линия', '2-я линия'],
  ])('«%s» и «%s» — разные улицы', (a, b) => {
    expect(streetKey(a)).not.toBe(streetKey(b));
  });
});
