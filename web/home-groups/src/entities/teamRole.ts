/**
 * Чем человек занимается в команде — по роли в «Справочник → Координаторы» (её пишут словами). От этого зависит, что
 * он видит сразу после входа по своему паролю:
 *  • распределитель обзванивает «хочу в группу» — по умолчанию свои и ничьи заявки;
 *  • координатор наполняет и проверяет группы — по умолчанию свои группы и свои обращения «хочу открыть группу»;
 *  • старший координатор смотрит за всеми — без отборов.
 * Роль, которую не узнали (или вход не связан со справочником), отборов не ставит.
 */
export type TeamKind = 'distributor' | 'coordinator' | 'senior' | null;

export function teamKindOf(role: string | null | undefined): TeamKind {
  const r = (role ?? '').toLowerCase();
  if (r.includes('распределител')) return 'distributor';
  if (r.includes('старш')) return 'senior';
  if (r.includes('координатор')) return 'coordinator';
  return null;
}
