import { describe, expect, test } from 'vitest';
import { dialNumber } from './phone';

describe('номер для ссылок «Позвонить» и «Написать»', () => {
  test('из отформатированного номера берутся только цифры с плюсом', () => {
    expect(dialNumber('+7 921 555-00-11')).toBe('+79215550011');
  });

  test('российский номер с восьмёрки приводится к +7', () => {
    expect(dialNumber('8 (921) 555-00-11')).toBe('+79215550011');
  });

  test('десять цифр без кода страны считаются российским номером', () => {
    expect(dialNumber('921 555-00-11')).toBe('+79215550011');
  });

  test('номер из одних цифр с семёрки получает плюс', () => {
    expect(dialNumber('79111242418')).toBe('+79111242418');
  });

  test('зарубежный номер остаётся как есть, только с плюсом', () => {
    expect(dialNumber('+375 29 123-45-67')).toBe('+375291234567');
  });

  test('пустое значение и текст без цифр — не номер', () => {
    expect(dialNumber('')).toBeNull();
    expect(dialNumber(null)).toBeNull();
    expect(dialNumber('нет телефона')).toBeNull();
  });

  test('слишком короткий набор цифр — не номер, звонить по нему нечем', () => {
    expect(dialNumber('12-34')).toBeNull();
  });
});
