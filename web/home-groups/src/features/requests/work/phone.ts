/**
 * Номер для ссылок `tel:` и `sms:`: плюс и цифры, без пробелов и дефисов.
 *
 * В заявке номер уже приведён сервером к «+7 921 555-00-11», но в демо и в старых строках из
 * таблицы он бывает «89215550011» или «921 555-00-11»: ссылка с лишними знаками на телефоне
 * не набирается. Российские номера приводим к +7, остальные оставляем со своим кодом страны.
 */
export function dialNumber(phone: string | null | undefined): string | null {
  const digits = (phone ?? '').replace(/\D/g, '');
  // Меньше семи цифр — это не номер, а обрывок: ссылка по нему ничего не наберёт.
  if (digits.length < 7) return null;
  if (digits.length === 11 && digits[0] === '8') return `+7${digits.slice(1)}`;
  if (digits.length === 10) return `+7${digits}`;
  return `+${digits}`;
}
