import { describe, expect, test } from 'vitest';
import { toCsv } from './csv';

describe('toCsv', () => {
  test('кириллица идёт с BOM, строки разделены «;» и CRLF', () => {
    expect(toCsv(['ФИО', 'Район'], [['Анна', 'Север']])).toBe('﻿ФИО;Район\r\nАнна;Север\r\n');
  });

  test('кавычки, «;» и переносы строк экранируются, пустое и null — пустая ячейка', () => {
    expect(toCsv(['a', 'b', 'c'], [['он "сказал"; ушёл', 'в\nдва', null]])).toBe(
      '﻿a;b;c\r\n"он ""сказал""; ушёл";"в\nдва";\r\n',
    );
  });

  test('текст, похожий на формулу, помечается апострофом, а отрицательные числа — нет', () => {
    expect(toCsv(['x'], [['=1+1'], ['@cmd'], [-5]])).toBe("﻿x\r\n'=1+1\r\n'@cmd\r\n-5\r\n");
  });
});
